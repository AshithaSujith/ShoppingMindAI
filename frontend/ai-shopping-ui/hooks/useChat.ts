import { useEffect, useRef, useState } from "react";

import type {
  Message,
  SessionEntry,
  Product,
  BackendResponse,
  CanonicalProduct,
    LoadingContent,
  Card,
} from "@/types";

import { clearSession, scrapeProducts, searchProducts } from "@/services/api";
import { normalizeProducts } from "@/utils/normalizeProducts";

const isGreetingText = (text: string) => {
  const words = text.toLowerCase().replace(/[^a-z\s]/g, " ").split(/\s+/).filter(Boolean)
  if (!words.length || words.length > 6) return false
  const greetingWords = new Set(["hi", "hai", "hello", "hey", "yo", "sup", "namaste", "namaskar"])
  const politeWords = new Set(["there", "everyone", "friend", "good", "morning", "afternoon", "evening", "day"])
  return words.some((word) => greetingWords.has(word)) && words.every((word) => greetingWords.has(word) || politeWords.has(word))
}

